// Create a class KiloToMiles for converting the distance kilometer to miles 

public class KiloToMiles{
	
	public static void main(String args[]){
		
		//Create the variable for kiloMeter
		float kiloMeter = 10.8f;
		
		//Create the variable for miles
		float miles = kiloMeter / 1.6f;
		
		
		
		//Print the converted value kilometre to miles 
		System.out.println(" The distance "+ kiloMeter +" km in miles is "+miles);
		
		
	}
}